const fs = require('fs');
const path = require('path');

const extensionId = process.argv[2];
const extensionName = process.argv[3] || 'My New Extension';

if (!extensionId) {
  console.error('Usage: node scaffold-extension.js <extension-id> "[Extension Name]"');
  process.exit(1);
}

const targetPath = path.resolve(__dirname, '..', extensionId);

if (fs.existsSync(targetPath)) {
  console.error(`Error: Extension directory already exists at ${targetPath}`);
  process.exit(1);
}

// Create directory
fs.mkdirSync(targetPath, { recursive: true });

// Create manifest
const manifest = {
  id: extensionId,
  name: extensionName,
  description: `A custom extension named ${extensionName} generated by AgentForgeMD.`,
  version: '1.0.0',
  author: 'AI Agent Developer',
  category: 'Custom Extensions',
  enabled: true,
  config: {}
};

fs.writeFileSync(
  path.join(targetPath, 'extension.json'),
  JSON.stringify(manifest, null, 2)
);

// Create README.md
const readme = `# ${extensionName}

This custom extension adds specialized agent guidelines, prompts, and templates to your editor.

## Instructions
1. Customize the metadata and configuration in \`extension.json\`.
2. Add your custom instructions and guidelines here.
`;

fs.writeFileSync(path.join(targetPath, 'README.md'), readme);

console.log(`\n✅ Successfully scaffolded new extension: ${extensionName}`);
console.log(`Directory: ${targetPath}`);
console.log(`Files created:\n  - extension.json\n  - README.md\n`);
